export const strings: Record<Lang, Strings> = { es, en };

/** Lee el campo en el idioma elegido, por ejemplo pick(item, 'name', 'en') → item.name_en. */
export function pick(obj: object, field: string, lang: Lang): string {
  const o = obj as Record<string, unknown>;
  return String(o[`${field}_${lang}`] || o[`${field}_es`] || '');
}
